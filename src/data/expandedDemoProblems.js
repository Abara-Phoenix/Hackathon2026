const multipleChoice = (
  id,
  skillId,
  difficulty,
  prompt,
  labels,
  correctIndex,
  hints,
  explanation,
  codeSnippet,
) => {
  const choices = labels.map((label, index) => ({
    id: `${id}-choice-${index + 1}`,
    label,
  }))

  return {
    id,
    skillId,
    difficulty,
    prompt,
    ...(codeSnippet ? { codeSnippet } : {}),
    choices,
    answer: choices[correctIndex].id,
    hints,
    explanation,
  }
}

